#!/usr/bin/env python3
"""
export_model.py — Stage 3 (Day 2): export artifacts the C side consumes.

Per model (models/quant/<name>/graph.json + tensors.npz) emits into models/export/<name>/:
  model.json      final Contract-2 graph incl. arena_size_bytes
  model_data.c/.h const int8 weights / int32 biases / double scales / softmax LUT
  golden/         per-layer + full-model vectors: JSON (interchange) + vectors.h/.c
                  (C tests link data directly — zero parsing on device, Contract 3)
  manifest.json   SHA-256 of every artifact (stale-vector protection)

--selftest runs the GATE 3 round-trip: re-parse model_data.c, compare weights
bit-exactly, re-simulate, compare outputs against the emitted golden vectors.
"""
import hashlib
import json
import os
import re
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from tinyml import contract_math as cm  # noqa: E402
import simulate as sim                  # noqa: E402

ROOT = os.path.dirname(HERE)
QUANT = os.path.join(ROOT, "models", "quant")
FP32 = os.path.join(ROOT, "models", "fp32")
EXPORT = os.path.join(ROOT, "models", "export")
N_FULL_VECTORS = 8
N_PER_LAYER_SAMPLES = 1

MODELS = ("mlp_demo", "cnn_demo")


# ---------------------------------------------------------------------------

def tensor_bytes(shape):
    n = 1
    for d in shape:
        n *= int(d)
    return n  # int8 = 1 byte per element


def arena_from_graph(graph):
    """Contract 2: arena = max over consecutive layer pairs of (out_n + out_{n+1})."""
    outs = [tensor_bytes(L["out_shape"]) for L in graph["layers"]]
    return max(outs[i] + outs[i + 1] for i in range(len(outs) - 1)) if len(outs) > 1 else outs[0]


def c_array_decl(dtype, name, values, per_line=12):
    vals = list(values)
    lines = []
    for i in range(0, len(vals), per_line):
        chunk = ", ".join(str(int(v)) for v in vals[i:i + per_line])
        lines.append("    " + chunk + ",")
    body = "\n".join(lines).rstrip(",")
    return f"const {dtype} {name}[{len(vals)}] = {{\n{body}\n}};\n"


def c_double_array(name, values, per_line=4):
    vals = list(values)
    lines = []
    for i in range(0, len(vals), per_line):
        chunk = ", ".join(repr(float(v)) for v in vals[i:i + per_line])
        lines.append("    " + chunk + ",")
    body = "\n".join(lines).rstrip(",")
    return f"const double {name}[{len(vals)}] = {{\n{body}\n}};\n"


def emit_model_data(graph, tensors):
    """Return (header_text, source_text)."""
    m = graph["model_name"].upper()
    h = [f"/* model_data.h — AUTO-GENERATED by tools/export_model.py for "
         f"{graph['model_name']}. DO NOT EDIT.\n"
         f" * Weights row-major, layouts per docs/CONTRACT_2_MODEL_JSON_SCHEMA.md.\n"
         f" * Requantize in C must compute requant_scale = (scale_in*scale_w)/scale_out\n"
         f" * in doubles — same order as the exporter (CONTRACT_1 §2). */\n"
         f"#ifndef MODEL_DATA_{m}_H\n#define MODEL_DATA_{m}_H\n\n"
         f"#include <stdint.h>\n\n"
         f"#define {m}_ARENA_SIZE {arena_from_graph(graph)}\n"]
    c = [f"/* model_data.c — AUTO-GENERATED for {graph['model_name']}. DO NOT EDIT. */\n"
         f'#include "model_data.h"\n\n']
    for L in graph["layers"]:
        if L["type"] in ("fc", "conv1d"):
            w, b = tensors[L["weight"]], tensors[L["bias"]]
            h.append(f"extern const int8_t {L['weight']}[{w.size}];\n")
            h.append(f"extern const int32_t {L['bias']}[{b.size}];\n")
            c.append(c_array_decl("int8_t", L["weight"], w.reshape(-1)))
            c.append(c_array_decl("int32_t", L["bias"], b.reshape(-1)))
            h.append(f"extern const double {L['name']}_scale_in;\n")
            h.append(f"extern const double {L['name']}_scale_w;\n")
            h.append(f"extern const double {L['name']}_scale_out;\n")
            h.append(f"extern const int {L['name']}_zp_in;\n")
            h.append(f"extern const int {L['name']}_zp_out;\n")
            c.append(f"const double {L['name']}_scale_in = {repr(float(L['scale_in']))};\n")
            c.append(f"const double {L['name']}_scale_w = {repr(float(L['scale_w']))};\n")
            c.append(f"const double {L['name']}_scale_out = {repr(float(L['scale_out']))};\n")
            c.append(f"const int {L['name']}_zp_in = {int(L['zp_in'])};\n")
            c.append(f"const int {L['name']}_zp_out = {int(L['zp_out'])};\n")
        elif L["type"] == "softmax":
            lut = cm.build_softmax_lut(L["zp_in"], L["scale_in"])
            h.append(f"extern const double {L['lut_ref']}[256];\n")
            c.append(c_double_array(L["lut_ref"], lut))
    h.append(f"#endif /* MODEL_DATA_{m}_H */\n")
    return "".join(h), "".join(c)


