# GATE 3: round-trip — parse generated C back, re-simulate, compare
# ---------------------------------------------------------------------------

ARRAY_RE = re.compile(
    r"const\s+(int8_t|int32_t|double)\s+(\w+)\[(\d+)\]\s*=\s*\{([^}]*)\}", re.S)


def parse_c_arrays(c_text):
    """Return dict name -> np.array with exact dtype."""
    out = {}
    for dtype, name, n, body in ARRAY_RE.findall(c_text):
        vals = [v.strip() for v in body.replace("\n", " ").split(",") if v.strip()]
        assert len(vals) == int(n), f"{name}: expected {n} values, got {len(vals)}"
        np_dtype = {"int8_t": np.int8, "int32_t": np.int32, "double": np.float64}[dtype]
        out[name] = np.array([float(v) for v in vals], dtype=np_dtype)
    return out


def roundtrip_test(model_name, out_dir, Xn, split):
    c_text = open(os.path.join(out_dir, "model_data.c")).read()
    parsed = parse_c_arrays(c_text)

    graph, tensors = sim.load_bundle(model_name)
    # 1) every exported tensor must survive the C round-trip bit-exactly
    for L in graph["layers"]:
        if L["type"] in ("fc", "conv1d"):
            assert np.array_equal(parsed[L["weight"]].reshape(tensors[L["weight"]].shape),
                                  tensors[L["weight"]]), f"{L['weight']} mismatch"
            assert np.array_equal(parsed[L["bias"]].reshape(tensors[L["bias"]].shape),
                                  tensors[L["bias"]]), f"{L['bias']} mismatch"

    # 2) re-simulate using ONLY the parsed C arrays + graph.json scales
    tensors2 = dict(tensors)
    for L in graph["layers"]:
        if L["type"] in ("fc", "conv1d"):
            tensors2[L["weight"]] = parsed[L["weight"]].reshape(tensors[L["weight"]].shape)
            tensors2[L["bias"]] = parsed[L["bias"]].reshape(tensors[L["bias"]].shape)

    inp = graph["input"]
    test_idx = split["test"]
    for i in test_idx[:N_FULL_VECTORS]:
        q_in = sim.quantize_input(Xn[int(i)], inp["scale"], inp["zero_point"]).reshape(inp["shape"])
        q_out = sim.simulate_model(graph, tensors2, q_in)
        # compare against the golden JSON emitted earlier
        gj = json.load(open(os.path.join(out_dir, "golden", "full_model.json")))
        k = list(test_idx[:N_FULL_VECTORS]).index(i)
        expected = np.array(gj["outputs"][k], dtype=np.int8)
        assert np.array_equal(q_out.reshape(-1), expected), \
            f"round-trip output mismatch on sample {k}"
    print(f"  round-trip {model_name}: weights bit-exact, outputs bit-exact  -> PASS")


def main():
    split = np.load(os.path.join(FP32, "split.npz"))
    Xn = np.load(os.path.join(FP32, "X_norm.npy"))
    print("== Stage 3: export ==")
    dirs = {}
    for m in MODELS:
        dirs[m] = export_model(m, Xn, split)
    print("== GATE 3: exporter round-trip ==")
    for m in MODELS:
        roundtrip_test(m, dirs[m], Xn, split)
    print("GATE 3 (export + round-trip): PASS")


if __name__ == "__main__":
    main()
