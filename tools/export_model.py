def golden_for_sample(graph, tensors, q_in):
    """Run with trace; return list of (layer_name, in_int8_flat, out_int8_flat)."""
    trace = []
    sim.simulate_model(graph, tensors, q_in, trace)
    return [(n, np.asarray(i).reshape(-1), np.asarray(o).reshape(-1))
            for (n, i, o) in trace]


def emit_golden(graph, tensors, Xn, split):
    """Return (json_files: dict[name->text], vectors_h, vectors_c)."""
    m = graph["model_name"].upper()
    inp = graph["input"]
    test_idx = split["test"]

    # ---- sample 0: per-layer trace (JSON + C) ----
    i0 = int(test_idx[0])
    q_in0 = sim.quantize_input(Xn[i0], inp["scale"], inp["zero_point"]).reshape(inp["shape"])
    trace = golden_for_sample(graph, tensors, q_in0)

    json_files = {}
    json_files["L00_input.json"] = json.dumps({
        "format_version": "0.1", "model_name": graph["model_name"],
        "layer_index": 0, "layer_name": "input", "layer_type": "input",
        "input": {"data": q_in0.reshape(-1).tolist(), "shape": inp["shape"]},
        "output": {"data": q_in0.reshape(-1).tolist(), "shape": inp["shape"]},
        "tolerance": 0}, indent=1)
    for li, (name, qin, qout) in enumerate(trace, start=1):
        L = graph["layers"][li - 1]
        json_files[f"L{li:02d}_{name}.json"] = json.dumps({
            "format_version": "0.1", "model_name": graph["model_name"],
            "layer_index": li, "layer_name": name, "layer_type": L["type"],
            "input": {"data": qin.tolist(), "shape": L["in_shape"]},
            "output": {"data": qout.tolist(), "shape": L["out_shape"]},
            "tolerance": 0}, indent=1)

    # ---- N_FULL_VECTORS: full-model in/out (JSON + C) ----
    full_ins, full_outs = [], []
    for i in test_idx[:N_FULL_VECTORS]:
        q_in = sim.quantize_input(Xn[int(i)], inp["scale"], inp["zero_point"]).reshape(inp["shape"])
        q_out = sim.simulate_model(graph, tensors, q_in)
        full_ins.append(q_in.reshape(-1).tolist())
        full_outs.append(q_out.reshape(-1).tolist())
    json_files["full_model.json"] = json.dumps({
        "format_version": "0.1", "model_name": graph["model_name"],
        "num_samples": len(full_ins),
        "input_shape": inp["shape"], "output_shape": graph["output"]["shape"],
        "inputs": full_ins, "outputs": full_outs, "tolerance": 0}, indent=1)

    # ---- C headers: per-layer (sample 0) + full-model (8 samples) ----
    vh = [f"/* vectors.h — AUTO-GENERATED golden vectors for {graph['model_name']}. "
          f"DO NOT EDIT. Contract 3. */\n"
          f"#ifndef GOLDEN_{m}_H\n#define GOLDEN_{m}_H\n\n"
          f"#include <stdint.h>\n\n"
          f"typedef struct {{ const char *name; int in_len; const int8_t *in; "
          f"int out_len; const int8_t *out; }} golden_vec_t;\n\n"
          f"#define GOLDEN_{m}_N_LAYERS {len(trace)}\n"
          f"extern const golden_vec_t GOLDEN_{m}_LAYERS[GOLDEN_{m}_N_LAYERS];\n\n"
          f"#define GOLDEN_{m}_N_SAMPLES {len(full_ins)}\n"
          f"#define GOLDEN_{m}_IN_LEN {len(full_ins[0])}\n"
          f"#define GOLDEN_{m}_OUT_LEN {len(full_outs[0])}\n"
          f"extern const int8_t GOLDEN_{m}_FULL_IN[GOLDEN_{m}_N_SAMPLES * GOLDEN_{m}_IN_LEN];\n"
          f"extern const int8_t GOLDEN_{m}_FULL_OUT[GOLDEN_{m}_N_SAMPLES * GOLDEN_{m}_OUT_LEN];\n\n"
          f"#endif /* GOLDEN_{m}_H */\n"]
    vc = [f'/* vectors.c — AUTO-GENERATED golden vectors for {graph["model_name"]}. */\n'
          f'#include "vectors.h"\n\n']
    for li, (name, qin, qout) in enumerate(trace):
        vc.append(c_array_decl("int8_t", f"GOLDEN_{m}_L{li:02d}_IN", qin))
        vc.append(c_array_decl("int8_t", f"GOLDEN_{m}_L{li:02d}_OUT", qout))
    entries = ",\n".join(
        f'    {{ "{name}", {len(qin)}, GOLDEN_{m}_L{li:02d}_IN, '
        f'{len(qout)}, GOLDEN_{m}_L{li:02d}_OUT }}'
        for li, (name, qin, qout) in enumerate(trace))
    vc.append(f"const golden_vec_t GOLDEN_{m}_LAYERS[GOLDEN_{m}_N_LAYERS] = {{\n{entries}\n}};\n\n")
    vc.append(c_array_decl("int8_t", f"GOLDEN_{m}_FULL_IN",
                           [v for s in full_ins for v in s]))
    vc.append(c_array_decl("int8_t", f"GOLDEN_{m}_FULL_OUT",
                           [v for s in full_outs for v in s]))
    return json_files, "".join(vh), "".join(vc)


