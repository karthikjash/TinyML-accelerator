def export_model(model_name, Xn, split):
    graph, tensors = sim.load_bundle(model_name)
    out_dir = os.path.join(EXPORT, model_name)
    golden_dir = os.path.join(out_dir, "golden")
    os.makedirs(golden_dir, exist_ok=True)

    # final model.json (Contract 2 complete form)
    model_json = dict(graph)
    model_json["arena_size_bytes"] = arena_from_graph(graph)
    with open(os.path.join(out_dir, "model.json"), "w") as f:
        json.dump(model_json, f, indent=2)

    # model_data.c/.h
    h_text, c_text = emit_model_data(model_json, tensors)
    with open(os.path.join(out_dir, "model_data.h"), "w") as f:
        f.write(h_text)
    with open(os.path.join(out_dir, "model_data.c"), "w") as f:
        f.write(c_text)

    # golden vectors
    json_files, vh, vc = emit_golden(model_json, tensors, Xn, split)
    for fname, text in json_files.items():
        with open(os.path.join(golden_dir, fname), "w") as f:
            f.write(text)
    with open(os.path.join(golden_dir, "vectors.h"), "w") as f:
        f.write(vh)
    with open(os.path.join(golden_dir, "vectors.c"), "w") as f:
        f.write(vc)

    # manifest with SHA-256 of everything
    def sha(path):
        return hashlib.sha256(open(path, "rb").read()).hexdigest()
    manifest = {
        "format_version": "0.1",
        "model_name": model_name,
        "generator": "tools/export_model.py v0.1",
        "num_layers": len(model_json["layers"]),
        "arena_size_bytes": model_json["arena_size_bytes"],
        "sha256": {
            "model.json": sha(os.path.join(out_dir, "model.json")),
            "model_data.h": sha(os.path.join(out_dir, "model_data.h")),
            "model_data.c": sha(os.path.join(out_dir, "model_data.c")),
            "vectors.h": sha(os.path.join(golden_dir, "vectors.h")),
            "vectors.c": sha(os.path.join(golden_dir, "vectors.c")),
        },
    }
    with open(os.path.join(out_dir, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2)
    print(f"  {model_name}: arena={model_json['arena_size_bytes']}B  "
          f"layers={manifest['num_layers']}  vectors={len(json_files)}+hdrs")
    return out_dir


